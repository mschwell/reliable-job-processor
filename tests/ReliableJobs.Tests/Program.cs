using System.Text.Json;
using Npgsql;
using ReliableJobs.Api.Database;
using ReliableJobs.Api.Jobs;

// Dependency-light console test harness: unit checks always run, PostgreSQL
// integration tests run when TEST_POSTGRES is supplied. GitHub CI supplies it.
var passed = 0;
var failed = 0;

async Task Test(string name, Func<Task> assertion)
{
    try
    {
        await assertion();
        Console.WriteLine($"PASS {name}");
        passed++;
    }
    catch (Exception ex)
    {
        Console.Error.WriteLine($"FAIL {name}: {ex}");
        failed++;
    }
}

static void Ensure(bool condition, string message)
{
    if (!condition) throw new Exception(message);
}

static EnqueueRequest Request(string kind, string payload, string? key = null, int attempts = 3)
    => new(kind, JsonSerializer.Deserialize<JsonElement>(payload), key, MaxAttempts: attempts);

await Test("retry policy is bounded and monotonic", () =>
{
    var values = Enumerable.Range(1, 12).Select(JobPolicy.RetryDelaySeconds).ToArray();
    Ensure(values[0] == 2 && values[1] == 4 && values[5] == 60, "Wrong backoff");
    Ensure(values.Zip(values.Skip(1)).All(x => x.First <= x.Second), "Backoff decreased");
    return Task.CompletedTask;
});

await Test("payload validation rejects bad and accepts good inputs", () =>
{
    Ensure(JobPolicy.Validate(Request("sum", "{\"numbers\":[1,2,3]}")) is null, "Valid sum rejected");
    Ensure(JobPolicy.Validate(Request("sum", "{\"numbers\":[]}")) is not null, "Empty array accepted");
    Ensure(JobPolicy.Validate(Request("delay", "{\"milliseconds\":9999}")) is not null, "Unbounded work accepted");
    Ensure(JobPolicy.Validate(Request("flaky", "{\"failUntilAttempt\":\"2\"}")) is not null, "String attempt accepted");
    Ensure(JobPolicy.Validate(Request("unknown", "{}")) is not null, "Unknown kind accepted");
    return Task.CompletedTask;
});

await Test("handler returns deterministic sum and simulated failures", async () =>
{
    var data = JsonSerializer.Deserialize<JsonElement>("{\"numbers\":[3,4,5]}");
    var claimed = new ClaimedJob(Guid.NewGuid(), "sum", data, 1, 3, Guid.NewGuid());
    var output = await JobHandler.ExecuteAsync(claimed, CancellationToken.None);
    Ensure(JsonDocument.Parse(output).RootElement.GetProperty("sum").GetDecimal() == 12m, "Wrong sum");
    var flaky = claimed with
    {
        Kind = "flaky", Payload = JsonSerializer.Deserialize<JsonElement>("{\"failUntilAttempt\":1}")
    };
    var threw = false;
    try { await JobHandler.ExecuteAsync(flaky, CancellationToken.None); }
    catch (InvalidOperationException) { threw = true; }
    Ensure(threw, "First attempt should fail");
    var succeeded = await JobHandler.ExecuteAsync(flaky with { Attempt = 2 }, CancellationToken.None);
    Ensure(succeeded.Contains("Success after retry"), "Second attempt should succeed");
});

var testConn = Environment.GetEnvironmentVariable("TEST_POSTGRES");
if (string.IsNullOrWhiteSpace(testConn))
{
    Console.WriteLine("SKIP PostgreSQL integration tests (set TEST_POSTGRES to enable).");
}
else
{
    // Each invocation uses its own PostgreSQL schema, avoiding interference with app data.
    // Schema name is randomly generated by us, never composed from untrusted input.
    var schema = "qa_" + Guid.NewGuid().ToString("N");
    await using var admin = NpgsqlDataSource.Create(testConn);
    await using (var cmd = admin.CreateCommand($"CREATE SCHEMA {schema};"))
        await cmd.ExecuteNonQueryAsync();
    try
    {
        var builder = new NpgsqlConnectionStringBuilder(testConn) { SearchPath = schema };
        await using var db = NpgsqlDataSource.Create(builder.ConnectionString);
        await new DbBootstrapper(db).InitializeAsync();
        var repo = new JobRepository(db);

        await Test("idempotency: replay returns same id; different payload conflicts", async () =>
        {
            var key = "dedup-" + Guid.NewGuid();
            var initial = Request("sum", "{\"numbers\":[1,2]}", key);
            var a = await repo.EnqueueAsync(initial);
            var b = await repo.EnqueueAsync(initial);
            var c = await repo.EnqueueAsync(Request("sum", "{\"numbers\":[1,3]}", key));
            Ensure(!a.Existing && !a.Conflict, "First enqueue did not create");
            Ensure(a.Id == b.Id && b.Existing && !b.Conflict, "Replay did not deduplicate");
            Ensure(c.Id == a.Id && c.Conflict, "Conflicting key not rejected");
            var claimed = await repo.ClaimNextAsync(30);
            Ensure(claimed?.Id == a.Id, "Unexpected job claimed");
            Ensure(await repo.RecordEffectAsync(claimed!.Id, claimed.LeaseToken, "{\"sum\":3}"), "Effect not inserted");
            Ensure(!await repo.RecordEffectAsync(claimed.Id, claimed.LeaseToken, "{\"sum\":3}"), "Effect was duplicated");
            Ensure(await repo.CompleteAsync(claimed.Id, claimed.LeaseToken), "Completion failed");
            var result = await repo.GetAsync(a.Id);
            Ensure(result?.Status == "succeeded" && result.Output?.GetProperty("sum").GetInt32() == 3, "Output missing");
            var history = await repo.HistoryAsync(a.Id);
            Ensure(history.Count == 1 && history[0].Outcome == "succeeded", "History wrong");
        });

        await Test("concurrent workers claim distinct jobs", async () =>
        {
            var ids = new HashSet<Guid>();
            for (var i = 0; i < 12; i++)
            {
                var created = await repo.EnqueueAsync(Request("sum", "{\"numbers\":[10,20]}"));
                ids.Add(created.Id);
            }
            // Each worker opens its own connection through the pooled NpgsqlDataSource.
            var claims = await Task.WhenAll(Enumerable.Range(0, 12)
                .Select(_ => repo.ClaimNextAsync(30)));
            Ensure(claims.All(c => c is not null), "Some jobs were not claimed");
            Ensure(claims.Select(c => c!.Id).Distinct().Count() == 12, "Duplicate claim occurred");
            Ensure(claims.All(c => ids.Contains(c!.Id)), "Claimed unrelated job");
            foreach (var job in claims)
            {
                Ensure(await repo.CompleteAsync(job!.Id, job.LeaseToken), "Could not complete claim");
                Ensure(!await repo.CompleteAsync(job.Id, job.LeaseToken), "Acknowledged twice");
            }
        });

        await Test("failure retries, dead-letter, and manual retry preserve history", async () =>
        {
            var original = await repo.EnqueueAsync(Request("flaky", "{\"failUntilAttempt\":3}", attempts: 2));
            for (var attempt = 1; attempt <= 2; attempt++)
            {
                var claimed = await repo.ClaimNextAsync(30);
                Ensure(claimed?.Id == original.Id && claimed.Attempt == attempt, "Incorrect attempt");
                Ensure(await repo.FailAsync(claimed!.Id, claimed.LeaseToken, "synthetic error", 0), "Failed to record retry");
            }
            var dead = await repo.GetAsync(original.Id);
            Ensure(dead?.Status == "dead" && dead.Attempts == 2, "Job not dead-lettered");
            Ensure(await repo.RetryDeadAsync(original.Id), "Manual retry refused");
            var third = await repo.ClaimNextAsync(30);
            Ensure(third?.Id == original.Id && third.Attempt == 3, "Attempt counter reset on manual retry");
            Ensure(await repo.CompleteAsync(third!.Id, third.LeaseToken), "Failed to complete retried job");
            var history = await repo.HistoryAsync(original.Id);
            Ensure(history.Select(x => x.AttemptNo).SequenceEqual(new[] { 1, 2, 3 }), "History lost on retry");
        });

        await Test("expired lease recovery fences stale acknowledgements", async () =>
        {
            var original = await repo.EnqueueAsync(Request("sum", "{\"numbers\":[6,7]}"));
            var old = await repo.ClaimNextAsync(30);
            Ensure(old?.Id == original.Id, "Job not claimed");
            // Simulate a crashed/paused worker using a forced expired lease.
            await using (var expire = db.CreateCommand("UPDATE jobs SET lease_expires_at = now() - interval '1 second' WHERE id = $1"))
            {
                expire.Parameters.AddWithValue(original.Id);
                await expire.ExecuteNonQueryAsync();
            }
            Ensure(!await repo.CompleteAsync(old!.Id, old.LeaseToken), "Expired owner completed job");
            Ensure(await repo.RecoverExpiredAsync() >= 1, "Expired lease not recovered");
            await using (var due = db.CreateCommand("UPDATE jobs SET available_at = now() WHERE id = $1"))
            {
                due.Parameters.AddWithValue(original.Id);
                await due.ExecuteNonQueryAsync();
            }
            var next = await repo.ClaimNextAsync(30);
            Ensure(next?.Id == original.Id && next.Attempt == 2, "Recovery did not create second attempt");
            Ensure(!await repo.FailAsync(old.Id, old.LeaseToken, "late owner", 0), "Stale failure changed job");
            Ensure(await repo.RecordEffectAsync(next!.Id, next.LeaseToken, "{\"sum\":13}"), "New lease cannot write effect");
            Ensure(await repo.CompleteAsync(next.Id, next.LeaseToken), "New lease failed completion");
            var history = await repo.HistoryAsync(original.Id);
            Ensure(history.Count == 2 && history[0].Outcome == "lease_expired" &&
                   history[1].Outcome == "succeeded", "Wrong recovery history");
        });
    }
    finally
    {
        await using var cleanup = admin.CreateCommand($"DROP SCHEMA IF EXISTS {schema} CASCADE;");
        await cleanup.ExecuteNonQueryAsync();
    }
}

Console.WriteLine($"RESULT {passed} passed; {failed} failed");
return failed == 0 ? 0 : 1;
